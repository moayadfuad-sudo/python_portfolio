# bool("") prints False because an empty string is false.
print(bool(""))

# bool("0") prints True because a non-empty string is true.
print(bool("0"))

# bool(0) prints False because zero is false.
print(bool(0))

# bool(0.0) prints False because zero is false.
print(bool(0.0))

# bool("False") prints True because it is a non-empty string.
print(bool("False"))